from datetime import datetime
from typing import Protocol
from uuid import UUID
from .entities import OAuthClient, AuthorizationCode, OAuthToken


class OAuthRepository(Protocol):
    def add(self, entity: OAuthClient | AuthorizationCode | OAuthToken) -> None: ...
    def client(self, client_id: str) -> OAuthClient | None: ...
    def client_by_id(self, identifier: UUID) -> OAuthClient | None: ...
    def lock_member(self, membership_id: UUID) -> None: ...
    def code(self, digest: str, *, lock: bool = False) -> AuthorizationCode | None: ...
    def token(self, digest: str, *, lock: bool = False) -> OAuthToken | None: ...
    def revoke_grant(self, grant_id: UUID, now: datetime) -> None: ...
    def revoke_member(self, membership_id: UUID, now: datetime) -> None: ...
    def revoke_tenant(self, tenant_id: UUID, now: datetime) -> None: ...
