from typing import Protocol
from uuid import UUID

from app.modules.mailboxes.domain.entities import Mailbox
from .entities import OutgoingMessage


class MailSender(Protocol):
    def send(self, mailbox: Mailbox, username: str, password: str, payload: dict, message_id: str) -> None: ...
    def check(self, mailbox: Mailbox, username: str, password: str) -> None: ...


class OutgoingRepository(Protocol):
    def add(self, message: OutgoingMessage) -> None: ...
    def get(self, tenant_id: UUID, membership_id: UUID, message_id: UUID) -> OutgoingMessage | None: ...
    def claim(self, message: OutgoingMessage) -> bool: ...
    def expire(self, tenant_id: UUID) -> None: ...
    def pending(self, tenant_id: UUID, membership_id: UUID) -> int: ...
